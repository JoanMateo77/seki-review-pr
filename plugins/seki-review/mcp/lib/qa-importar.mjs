// Import of filled QA guides: validates the file, turns each signed row into a qa_resultado event and re-derives the stages.
// The file is untrusted input: rows are matched by their signed key, never by position.
import { createHash, timingSafeEqual } from 'node:crypto';
import { closeSync, fstatSync, openSync, readSync, realpathSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, sep } from 'node:path';
import { secretoQa } from './acceso.mjs';
import { dirQa, leerJson, rutaEntregas, rutaInstantanea } from './cache.mjs';
import { expandir } from './config.mjs';
import { leerEventos, registrarEventos } from './eventos.mjs';
import { aplicarRastreador } from './rastreador-xlsx.mjs';
import { claveFusion, esMasNueva, firmaFila, fusionDePista, guiaVigente, leerGuias, tieneResultados } from './qa-guia.mjs';
import { COLUMNAS_SEKI, FORMATO_SEKI } from './qa-salida.mjs';
import { derivarEnSerie, enSerieEntregas } from './recolectar.mjs';
import { mapaPrs } from './tablero-entregas.mjs';
import { leerXlsx } from './xlsx.mjs';

export const MAX_ARCHIVO = 5 * 1024 * 1024;
const ETAPAS_QA = new Set(['esperando_qa', 'qa_fallo', 'listo_produccion']);
const ETAPAS_PROD = new Set(['en_produccion', 'cerrada']);
const MAX_ENCABEZADO = 10;
const MAX_TEXTO = 100;

const fallar = (codigo, mensaje) => {
  throw Object.assign(new Error(`[seki-review/qa] ${mensaje}`), { codigo });
};
const texto = (v) => String(v ?? '').trim();
const corto = (v) => texto(v).slice(0, MAX_TEXTO);
const llave = (etiqueta, portal) => JSON.stringify([etiqueta, portal]);

function firmaValida(esperada, recibida) {
  const a = Buffer.from(esperada, 'utf8');
  const b = Buffer.from(texto(recibida), 'utf8');
  return a.length === b.length && timingSafeEqual(a, b);
}

function prsDeCelda(valor) {
  try {
    const prs = JSON.parse(valor);
    return Array.isArray(prs) && prs.every((x) => typeof x === 'string') ? prs : null;
  } catch {
    return null;
  }
}

// Pure apart from reading the signing secret. `previos`: qa_resultado events already stored (identical rows are skipped).
export function analizarImportacion(p, buf, { entregas = [], guias = [], ahora = new Date(), prsPorId = new Map(), previos = [] } = {}) {
  const conocidos = new Set(previos.map((e) => e.id));
  const libro = leerXlsx(buf);
  const seki = libro.hojas.find((h) => h.nombre === '_seki');
  const visible = libro.hojas.find((h) => h.nombre === 'QA') ?? libro.hojas.find((h) => !h.oculta && h.nombre !== '_seki');
  if (!seki || !visible) fallar('QA_GUIA', 'The file is not a QA guide generated by this tool');
  const cabecera = seki.filas[0] ?? [];
  if (texto(cabecera[0]) !== FORMATO_SEKI) fallar('QA_GUIA', 'The guide format is not supported');
  if (texto(cabecera[2]) !== p.clave) fallar('QA_GUIA', 'The guide belongs to another project');
  const guia = guias.find((g) => g.id === texto(cabecera[1]));
  if (!guia) fallar('QA_GUIA', 'The guide is not registered: generate a new guide');

  const secreto = secretoQa(p);
  const registradas = new Map(guia.filas.map((f) => [llave(f.etiqueta, f.portal), f]));
  const firmadas = new Map();
  for (const fila of seki.filas.slice(1)) {
    const c = Object.fromEntries(COLUMNAS_SEKI.map((n, i) => [n, texto(fila[i])]));
    const prs = prsDeCelda(c.prs);
    const reg = registradas.get(llave(c.etiqueta, c.portal));
    if (!prs || !reg || reg.entrega !== c.entrega || claveFusion(reg.prs) !== claveFusion(prs)) continue;
    if (!firmaValida(firmaFila(secreto, { guia: guia.id, etiqueta: c.etiqueta, portal: c.portal, prs, entrega: c.entrega }), c.firma)) continue;
    firmadas.set(llave(c.etiqueta, c.portal), reg);
  }

  const nombres = (fila) => fila.map((c) => texto(c).toLowerCase());
  const iEnc = visible.filas.slice(0, MAX_ENCABEZADO).findIndex((f) => ['id', 'portal', 'result'].every((n) => nombres(f).includes(n)));
  if (iEnc < 0) fallar('QA_GUIA', 'The QA sheet has no ID, Portal and Result columns');
  const encabezado = nombres(visible.filas[iEnc]);
  const col = (nombre) => encabezado.indexOf(nombre.toLowerCase());
  const [iId, iPortal, iResultado, iTester] = [col('ID'), col('Portal'), col('Result'), col('Tester')];

  const mapeo = new Map(Object.entries(p.qa.mapeo).map(([k, v]) => [k.trim().toLowerCase(), v]));
  const archivo = createHash('sha256').update(buf).digest('hex');
  const eventos = [];
  const rechazadas = [];
  const grupos = new Map();
  const vistas = new Set();
  const pistas = entregas.flatMap((e) => (e.pistas ?? []).map((pista) => ({ entrega: e, pista })));

  for (const celdas of visible.filas.slice(iEnc + 1)) {
    const etiqueta = texto(celdas[iId]);
    const portal = texto(celdas[iPortal]);
    const bruto = texto(celdas[iResultado]);
    if (!etiqueta && !portal && !bruto) continue;
    const rechazar = (motivo) => rechazadas.push({ etiqueta: corto(etiqueta), portal: corto(portal), motivo });
    const registrada = firmadas.get(llave(etiqueta, portal));
    const vacio = bruto === '' || (mapeo.has(bruto.toLowerCase()) && mapeo.get(bruto.toLowerCase()) === null);
    if (!registrada) {
      if (!vacio) rechazar('Row key does not match the guide');
      continue;
    }
    if (vistas.has(llave(etiqueta, portal))) {
      if (!vacio) rechazar('Duplicate row');
      continue;
    }
    vistas.add(llave(etiqueta, portal));
    const propios = new Set(registrada.prs);
    const destino = pistas.find(({ pista }) => pista.portal === registrada.portal && pista.prs.some((id) => propios.has(id)));
    const grupo = () => {
      const k = JSON.stringify([registrada.entrega, registrada.portal]);
      if (!grupos.has(k)) grupos.set(k, { entrega: registrada.entrega, portal: registrada.portal, estados: [], ya: 0 });
      return grupos.get(k);
    };
    if (vacio) {
      grupo().estados.push('pendiente');
      continue;
    }
    if (!mapeo.has(bruto.toLowerCase())) {
      rechazar('Unrecognised result');
      continue;
    }
    const resultado = mapeo.get(bruto.toLowerCase());
    if (!['ok', 'fallo', 'bloqueado', 'na'].includes(resultado)) {
      rechazar('Unrecognised result');
      continue;
    }
    const id = createHash('sha256').update(`qa_resultado|${guia.id}#${registrada.etiqueta}@${registrada.portal}|${archivo}`).digest('hex');
    const estado = resultado === 'na' ? 'ok' : resultado;
    if (conocidos.has(id)) {
      const g = grupo();
      g.estados.push(estado);
      g.ya++;
      continue;
    }
    if (!destino || !(ETAPAS_QA.has(destino.pista.etapa) || ETAPAS_PROD.has(destino.pista.etapa))) {
      rechazar('The delivery is no longer waiting for QA');
      continue;
    }
    const vigente = guiaVigente(guias, { portal: registrada.portal, prs: registrada.prs }, previos);
    if (vigente && vigente.id !== guia.id && esMasNueva(vigente, guia) && tieneResultados(vigente, { portal: registrada.portal, prs: registrada.prs }, previos)) {
      rechazar('A newer guide covers this delivery: use the newest guide');
      continue;
    }
    if (ETAPAS_PROD.has(destino.pista.etapa)) {
      const guardado = previos.filter((e) => e.tipo === 'qa_resultado' && e.guia === guia.id && e.fila === registrada.etiqueta && e.portal === registrada.portal)
        .sort((a, b) => (a.ts < b.ts ? -1 : a.ts > b.ts ? 1 : (a.registrado ?? '') < (b.registrado ?? '') ? -1 : 1)).at(-1);
      if (guardado?.resultado === resultado) {
        const g = grupo();
        g.estados.push(estado);
        g.ya++;
      } else rechazar('The delivery is already in production');
      continue;
    }
    const fusionGuia = guia.fusiones?.[claveFusion(registrada.prs)];
    const actual = fusionDePista(destino.pista, prsPorId);
    if (actual && (!fusionGuia || actual > fusionGuia)) {
      rechazar('New testing merge after the guide: generate a new guide');
      continue;
    }
    eventos.push({
      id, ts: ahora.toISOString(), tipo: 'qa_resultado', entrega: registrada.entrega, prs: [...registrada.prs], portal: registrada.portal,
      guia: guia.id, fila: registrada.etiqueta, resultado, tester: iTester >= 0 ? corto(celdas[iTester]) : '', archivo, origen: 'qa',
    });
    grupo().estados.push(estado);
  }

  const resumen = [...grupos.values()].map((g) => ({
    entrega: g.entrega,
    portal: g.portal,
    resultado: g.estados.includes('fallo') ? 'fallo' : g.estados.includes('bloqueado') ? 'bloqueado' : g.estados.includes('pendiente') ? 'pendiente' : 'ok',
    filas: g.estados.length,
    ya_registradas: g.ya,
  }));
  return { guia: guia.id, eventos, resumen, rechazadas };
}

function leerArchivo(p, { ruta: entrada, confirmar }) {
  const ruta = expandir(entrada);
  if (typeof ruta !== 'string' || ruta === '' || !/\.xlsx$/i.test(ruta)) fallar('QA_RUTA', 'The file must be an .xlsx workbook');
  let real;
  try {
    real = realpathSync(ruta);
  } catch {
    fallar('QA_RUTA', 'The file does not exist');
  }
  if (!/\.xlsx$/i.test(real) || !statSync(real).isFile()) fallar('QA_RUTA', 'The path is not a regular .xlsx file');
  const raices = [dirQa(p.salida), join(homedir(), 'Downloads')].flatMap((r) => {
    try {
      return [realpathSync(r)];
    } catch {
      return [];
    }
  });
  if (!raices.some((r) => real === r || real.startsWith(r + sep)) && confirmar !== true) {
    fallar('QA_RUTA', 'The file is outside the QA output folder and Downloads: confirm the import explicitly');
  }
  // One descriptor for the size check and the read: the file cannot grow in between.
  const fd = openSync(real, 'r');
  try {
    const st = fstatSync(fd);
    if (!st.isFile()) fallar('QA_RUTA', 'The path is not a regular .xlsx file');
    if (st.size > MAX_ARCHIVO) fallar('QA_TAMANO', 'The file exceeds 5 MB');
    const b = Buffer.alloc(Math.min(st.size, MAX_ARCHIVO) + 1);
    let n = 0;
    for (let k; n < b.length && (k = readSync(fd, b, n, b.length - n, n)) > 0;) n += k;
    if (n > MAX_ARCHIVO) fallar('QA_TAMANO', 'The file exceeds 5 MB');
    return b.subarray(0, n);
  } finally {
    closeSync(fd);
  }
}

export async function importarQa(p, { buf, ruta, confirmar, ahora = new Date() } = {}) {
  if (buf === undefined && ruta === undefined) fallar('QA_VACIA', 'No file content was given');
  const datos = buf ?? leerArchivo(p, { ruta, confirmar });
  if (!Buffer.isBuffer(datos) && !(datos instanceof Uint8Array)) fallar('QA_VACIA', 'No file content was given');
  if (datos.length > MAX_ARCHIVO) fallar('QA_TAMANO', 'The file exceeds 5 MB');
  const contenido = Buffer.from(datos);
  return enSerieEntregas(async () => {
    const foto = leerJson(rutaInstantanea(p.salida));
    const base = leerJson(rutaEntregas(p.salida));
    if (!foto || !base) fallar('QA_SIN_ENTREGAS', 'There are no deliveries yet: refresh the state first');
    const previos = leerEventos(p).filter((e) => e.tipo === 'qa_resultado');
    const r = analizarImportacion(p, contenido, { entregas: base.entregas ?? [], guias: leerGuias(p).guias, ahora, prsPorId: mapaPrs(foto), previos });
    const { nuevos } = await registrarEventos(p, r.eventos, { ahora });
    if (nuevos) await derivarEnSerie(p, foto);
    // A refused or failed tracker write never undoes the recorded events.
    let rastreador = { escrito: false, motivo: 'No tracker configured' };
    if (p.qa?.rastreador) {
      try {
        rastreador = await aplicarRastreador(p, leerJson(rutaEntregas(p.salida))?.entregas ?? [], mapaPrs(foto), { ahora });
      } catch {
        rastreador = { escrito: false, celdas: 0, motivo: 'The tracker could not be updated' };
      }
    }
    return { guia: r.guia, resumen: r.resumen, rechazadas: r.rechazadas, nuevos, rastreador };
  });
}
